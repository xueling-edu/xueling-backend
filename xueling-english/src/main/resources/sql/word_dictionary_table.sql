CREATE TABLE `word_dictionary` (
    `id` bigint unsigned NOT NULL AUTO_INCREMENT COMMENT '词条ID',
    `word` varchar(255) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT '显示用词条',
    `word_key` varchar(255) COLLATE utf8mb4_bin NOT NULL COMMENT '规范化查询键',
    `meaning` mediumtext COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '中文原始释义或AI释义',
    `phonetic` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '音标',
    `definition` mediumtext COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '英文释义',
    `pos` varchar(255) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'ECDICT词性频率',
    `collins` tinyint unsigned DEFAULT NULL COMMENT '柯林斯星级',
    `oxford` tinyint unsigned DEFAULT NULL COMMENT '牛津核心词标记',
    `tag` text COLLATE utf8mb4_unicode_ci COMMENT '考试标签',
    `bnc` int unsigned DEFAULT NULL COMMENT 'BNC词频排名',
    `frq` int unsigned DEFAULT NULL COMMENT '当代语料库词频排名',
    `exchange` text COLLATE utf8mb4_unicode_ci COMMENT '词形变化',
    `detail` mediumtext COLLATE utf8mb4_unicode_ci COMMENT 'ECDICT扩展数据原文',
    `audio` varchar(1000) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'ECDICT音频地址',
    `source` varchar(20) COLLATE utf8mb4_unicode_ci NOT NULL COMMENT 'ECDICT、AI或AI_ENRICHED',
    `content_version` bigint unsigned NOT NULL DEFAULT 0 COMMENT '内容修改版本，供管理端并发检查',
    `dataset_version` varchar(64) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT 'ECDICT导入版本',
    `example` varchar(500) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '英文例句',
    `example_translation` varchar(500) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '例句翻译',
    `image_url` varchar(200) COLLATE utf8mb4_unicode_ci DEFAULT NULL COMMENT '插图地址',
    `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
    `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (`id`),
    UNIQUE KEY `uk_word_key` (`word_key`),
    KEY `idx_update_time` (`update_time` DESC)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='英汉词典';
